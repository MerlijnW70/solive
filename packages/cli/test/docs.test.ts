const cell = (text: string) => text.replaceAll("|", "\\|").replaceAll("\n", " ");

const page = (title: string, body: string[]) => [GENERATED, "", `# ${title}`, "", ...body].join("\n").trimEnd() + "\n";

function typeOf(json: Json): string {
  if (Array.isArray(json["anyOf"])) {
    const [inner] = json["anyOf"] as Json[];
    return `${typeOf(inner ?? {})} or null`;
  }
  if (json["const"] !== undefined) {
    return `\`${String(json["const"])}\``;
  }
  if (Array.isArray(json["enum"])) {
    return (json["enum"] as string[]).map((v) => `\`${v}\``).join(", ");
  }
  switch (json["pattern"]) {
    case ADDRESS_PATTERN:
      return "address";
    case AMOUNT_PATTERN:
      return "whole number as a decimal string";
    case TIME_PATTERN:
      return "unix seconds as a decimal string";
  }
  if (json["type"] === "integer") {
    return `integer ${String(json["minimum"])}..${String(json["maximum"])}`;
  }
  if (json["type"] === "array") {
    const least = Number(json["minItems"] ?? 0);
    const count = least > 0 ? `${least} to ${String(json["maxItems"])}` : `at most ${String(json["maxItems"])}`;
    return `list of ${typeOf((json["items"] as Json | undefined) ?? {})}, ${count}`;
  }
  if (Array.isArray(json["oneOf"])) {
    return "one of the shapes below";
  }
  return String(json["type"] ?? "any");
}

type Row = { path: string; type: string; required: boolean; description: string };

function rows(json: Json, prefix: string, required: boolean): Row[] {
  const description = typeof json["description"] === "string" ? json["description"] : "";
  const here = prefix === "" ? [] : [{ path: prefix, type: typeOf(json), required, description }];
  if (json["type"] === "object" && json["properties"] !== undefined) {
    const needed = new Set((json["required"] as string[] | undefined) ?? []);
    const props = Object.entries(json["properties"] as Record<string, Json>);
    const nested = props.flatMap(([k, v]) => rows(v, prefix === "" ? k : `${prefix}.${k}`, needed.has(k)));
    return [...here, ...nested];
  }
  if (Array.isArray(json["oneOf"])) {
    const shapes = (json["oneOf"] as Json[]).flatMap((shape) => {
      const props = shape["properties"] as Record<string, Json>;
      const [tag, value] = Object.entries(props).find(([, v]) => v["const"] !== undefined) ?? ["", {}];
      const label = `${prefix}[${tag}=${String(value["const"])}]`;
      const needed = new Set((shape["required"] as string[] | undefined) ?? []);
      return Object.entries(props)
        .filter(([k]) => k !== tag)
        .flatMap(([k, v]) => rows(v, `${label}.${k}`, needed.has(k)));
    });
    return [...here, ...shapes];
  }
  return here;
}

const table = (header: string[], body: string[][]) => [
  `| ${header.join(" | ")} |`,
  `| ${header.map(() => "---").join(" | ")} |`,
  ...body.map((r) => `| ${r.map(cell).join(" | ")} |`),
];

function cliPage(): string {
  const verbs = Object.keys(ACCEPTS);
  const body = verbs.flatMap((verb) => {
    const { usage, options } = usageOf(verb);
    const listed = (names: readonly string[]) => names.map((o) => `\`${o}\``).join(", ");
    const subs = Object.entries(SUB_ACCEPTS[verb] ?? {}).map(
      ([sub, names]) => `Options for \`${sub}\`: ${listed([...names, ...GLOBAL_OPTIONS].map((o) => `--${o}`))}`,
    );
    const lines = subs.length === 0 ? [`Options: ${listed(options)}`] : subs.flatMap((l) => [l, ""]).slice(0, -1);
    return [`## ${verb}`, "", "```text", usage, "```", "", ...lines, ""];
  });
  return page("CLI reference", [
    "```text",
    USAGE,
    "```",
    "",
    `Every command accepts ${GLOBAL_OPTIONS.map((o) => `\`--${o}\``).join(" and ")}.`,
    "",
    `\`${ENV_KEYPAIR}\` fills in \`--keypair\` and \`${ENV_URL}\` fills in \`--url\` when they are not given. \`--url\` takes an RPC URL or one of ${Object.keys(CLUSTERS).map((c) => `\`${c}\``).join(", ")}.`,
    "",
    ...body,
  ]);
}

function toolsPage(): string {
  const body = [...WALLET_ACTIONS, ...ACTIONS].flatMap((action) => {
    const hints = annotationsOf(action);
    const params = rows(action.input.json, "", true);
    return [
      `## ${action.name}`,
      "",
      ...(WALLET_ACTIONS.includes(action) ? ["Served only with `--wallet`.", ""] : []),
      action.description,
      "",
      `Effect: \`${action.effect}\` (read-only: ${String(hints.readOnlyHint)}, destructive: ${String(hints.destructiveHint)}, idempotent: ${String(hints.idempotentHint)})`,
      "",
      ...(params.length === 0
        ? ["Parameters: none", ""]
        : [...table(["Parameter", "Type", "Required", "Description"], params.map((r) => [`\`${r.path}\``, r.type, r.required ? "yes" : "no", r.description])), ""]),
    ];
  });
  return page("MCP tools", [
    `${ACTIONS.length} tools, served by \`intent-engine mcp\` over stdio. With \`--wallet\` it also serves the ${WALLET_ACTIONS.length} wallet tools, listed first.`,
    "",
    ...body,
  ]);
}

function errorsPage(): string {
  const engine = Object.entries(ENGINE_PROBLEMS).map(([name, p], i) => [
    String(ENGINE_ERROR_BASE + i),
    `\`${name}\``,
    p.retryable ? "yes" : "no",
    p.hint,
  ]);
  const token = Object.entries(TOKEN_PROBLEMS).map(([code, p]) => [code, `\`${p.code}\``, p.retryable ? "yes" : "no", p.hint]);
  const server = Object.entries(SERVER_PROBLEMS).map(([name, p]) => [`\`${name}\``, p.retryable ? "yes" : "no", p.hint]);
  return page("Errors", [
    "## This server",
    "",
    "Problems the MCP server reports itself, before it sends anything. The hint a tool returns names the specifics.",
    "",
    ...table(["Name", "Retry later", "When"], server),
    "",
    "## Engine program",
    "",
    ...table(["Code", "Name", "Retry later", "What to do"], engine),
    "",
    "## Token programs",
    "",
    ...table(["Code", "Name", "Retry later", "What to do"], token),
  ]);
}

const PAGES: Record<string, () => string> = {
  "reference/cli.md": cliPage,
  "reference/mcp-tools.md": toolsPage,
  "reference/errors.md": errorsPage,
};

const markdown = (dir: string): string[] =>
  readdirSync(dir, { withFileTypes: true }).flatMap((e) => (e.isDirectory() ? markdown(join(dir, e.name)) : e.name.endsWith(".md") ? [join(dir, e.name)] : []));

describe("doc links", () => {
  it("point at files that exist", () => {
    const pages = [`${ROOT}/README.md`, `${ROOT}/SECURITY.md`, `${ROOT}/CONTRIBUTING.md`, ...markdown(DOCS)];
    const broken = pages.flatMap((page) =>
      [...readFileSync(page, "utf8").matchAll(/\]\(([^)#]+)\)/g)]
        .map((m) => m[1] ?? "")
        .filter((target) => !/^https?:/.test(target))
        .filter((target) => !existsSync(join(dirname(page), target)))
        .map((target) => `${page}: ${target}`),
    );
    expect(pages.length).toBeGreaterThan(4);
    expect(broken).toEqual([]);
  });

  it("use no file name that coding tools load as instructions", () => {
    const reserved = new Set(["agents.md", "gemini.md"]);
    const pages = [`${ROOT}/README.md`, `${ROOT}/SECURITY.md`, `${ROOT}/CONTRIBUTING.md`, ...markdown(DOCS)];
    expect(pages.filter((page) => reserved.has(page.split(/[\/]/).pop()?.toLowerCase() ?? ""))).toEqual([]);
  });
});

describe("policy pages", () => {
  const read = (path: string) => readFileSync(`${ROOT}/${path}`, "utf8");
  const pick = (pattern: RegExp, text: string) => pattern.exec(text)?.[1] ?? "missing";

  it("name the contact and program the program itself publishes", () => {
    const security = read("SECURITY.md");
    const contact = pick(/contacts: "link:([^"]+)"/, read("programs/intent_engine/src/security.rs"));
    const program = pick(/declare_id!\("(\w+)"\)/, read("programs/intent_engine/src/lib.rs"));
    expect(security).toContain(`Report it privately at ${contact}.`);
    expect(security).toContain(`deployed from it at \`${program}\` on devnet`);
    expect(read("CONTRIBUTING.md")).toContain("Follow [SECURITY.md](SECURITY.md)");
    const issues = read(".github/ISSUE_TEMPLATE/config.yml");
    expect(issues).toContain("blank_issues_enabled: false\n");
    expect(issues).toContain(`    url: ${contact}\n`);
    expect(read(".github/ISSUE_TEMPLATE/bug.yml")).toContain("description: The output of `intent-engine version`.");
  });

  it("back every known behaviour with a test that exists", () => {
    const security = read("SECURITY.md");
    const section = security.slice(security.indexOf("## Known and accepted behaviour"), security.indexOf("## Rewards"));
    const named = [...section.matchAll(/`([a-z0-9]+(?:_[a-z0-9]+){3,})`/g)].map((m) => m[1] ?? "");
    const rust = (dir: string): string[] =>
      readdirSync(dir, { withFileTypes: true }).flatMap((e) =>
        e.isDirectory() ? rust(join(dir, e.name)) : e.name.endsWith(".rs") ? [readFileSync(join(dir, e.name), "utf8")] : [],
      );
    const sources = rust(`${ROOT}/tests/svm/tests`).join("\n");
    expect(named.length).toBeGreaterThan(9);
    expect(named.filter((name) => !sources.includes(`fn ${name}(`))).toEqual([]);
  });

  it("ask for the toolchain, scripts and CI jobs the repository declares", () => {
    const contributing = read("CONTRIBUTING.md");
    const ci = read(".github/workflows/ci.yml");
    const root = JSON.parse(read("package.json")) as { engines: { node: string }; packageManager: string };
    const [, major, minor] = /^>=(\d+)\.(\d+)\.0$/.exec(root.engines.node) ?? [];
    expect(contributing).toContain(`- Rust ${pick(/^channel = "([^"]+)"$/m, read("rust-toolchain.toml"))}, from \`rust-toolchain.toml\``);
    expect(contributing).toContain(`- Agave (Solana CLI) ${pick(/AGAVE_VERSION: (\S+)/, ci)}`);
    expect(contributing).toContain(`- Anchor CLI ${pick(/^anchor_version = "([^"]+)"$/m, read("Anchor.toml"))}`);
    expect(contributing).toContain(`- Node.js ${major}.${minor} or later and pnpm ${root.packageManager.replace("pnpm@", "")}`);
    const scripts = [...contributing.matchAll(/scripts\/[\w-]+\.sh/g)].map((m) => m[0]);
    expect(scripts.length).toBeGreaterThan(4);
    expect(scripts.filter((path) => !existsSync(`${ROOT}/${path}`))).toEqual([]);
    const jobs = [...ci.slice(ci.indexOf("\njobs:")).matchAll(/^ {2}([\w-]+):$/gm)].map((m) => m[1]);
    expect(jobs).toEqual(["check", "audit", "verifiable", "fuzz", "proofs", "sign-off"]);
    expect(pick(/run: bash scripts\/(\w+)\.sh/, ci.slice(ci.indexOf("  check:")))).toBe("ci");
    expect(ci.slice(ci.indexOf("  sign-off:"))).toContain("if: github.event_name == 'pull_request'");
    expect(contributing).toContain(
      "This builds the program, fails on any drift in generated files, lints, and runs the Rust and TypeScript test suites.",
    );
    const local = read("scripts/ci.sh");
    for (const step of ["bash scripts/build.sh", "bash scripts/codegen.sh", "git diff --exit-code", "bash scripts/lint.sh", "cargo test --workspace", "bash scripts/ts-test.sh"]) {
      expect(local, step).toContain(step);
    }
    expect(contributing).toContain("`scripts/comments.sh` enforces this; Anchor's `/// CHECK:` lines are the only exception.");
    expect(read("scripts/lint.sh")).toContain("bash scripts/comments.sh");
    expect(read("scripts/comments.sh")).toContain("/// CHECK:");
  });
});

describe("generated reference docs", () => {
  it("numbers engine errors exactly as the program's IDL does", () => {
    const idl = JSON.parse(readFileSync(IDL, "utf8")) as { errors: { code: number; name: string }[] };
    const pascal = (name: string) => name.charAt(0).toUpperCase() + name.slice(1);
    expect(idl.errors.map((e) => [e.code, pascal(e.name)])).toEqual(
      Object.keys(ENGINE_PROBLEMS).map((name, i) => [ENGINE_ERROR_BASE + i, name]),
    );
  });

  for (const [path, render] of Object.entries(PAGES)) {
    it(`${path} matches the code it is generated from`, () => {
      const file = `${DOCS}${path}`;
      const fresh = render();
      if (process.env["DOCS_WRITE"] === "1") {
        mkdirSync(dirname(file), { recursive: true });
        writeFileSync(file, fresh);
      }
      expect(existsSync(file)).toBe(true);
      expect(readFileSync(file, "utf8")).toBe(fresh);
    });
  }
});
