function engineErrorsPage(): string {
  const { errors } = JSON.parse(readFileSync(ENGINE_IDL, "utf8")) as { errors: { code: number; name: string }[] };
  const problems: Record<string, { retryable: boolean; hint: string }> = ENGINE_PROBLEMS;
  const body = errors.map(({ code, name }) => {
    const problem = problems[name];
    if (problem === undefined) {
      throw new Error(`${name} has no entry in ENGINE_PROBLEMS`);
    }
    return [String(code), `\`${name}\``, problem.retryable ? "yes" : "no", problem.hint.split("; ")[0] ?? ""];
  });
  return page("Engine errors", [
    "Every error the engine program raises, from its IDL. When an SDK call fails, `client.explain(error)` returns the code and name of the engine error behind it, or `null` if the engine raised none. Retry later `yes` means the cause can pass with time, so the same call can succeed later.",
    "",
    ...table(["Code", "Name", "Retry later", "Meaning"], body),
  ]);
}

